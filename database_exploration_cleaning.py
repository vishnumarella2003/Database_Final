def clean_matrix_to_long(
    df,
    output_filename,
    value_column_name,
    gene_source_name,
    is_rppa=False,
    chunk_size=1000
):
    """
    Converts wide matrix file into long format without creating SQL IDs.

    Output format for CNA and mRNA:
    - SAMPLE_BARCODE
    - HUGO_SYMBOL
    - VALUE_COLUMN

    Output format for RPPA:
    - SAMPLE_BARCODE
    - HUGO_SYMBOL
    - ANTIBODY_REF
    - EXPRESSION_VALUE
    """

    gene_col = identify_matrix_gene_column(df)
    annotation_cols = identify_matrix_annotation_columns(df)
    sample_cols = [c for c in df.columns if c not in annotation_cols]

    output_path = OUTPUT_DIR / output_filename

    if output_path.exists():
        output_path.unlink()

    first_write = True
    total_rows = 0
    gene_rows = []

    for start in range(0, len(df), chunk_size):
        chunk = df.iloc[start:start + chunk_size].copy()

        if is_rppa:
            feature_series = get_series(chunk, gene_col)
            chunk["HUGO_SYMBOL_CLEAN"] = feature_series.apply(parse_rppa_gene)
            chunk["ANTIBODY_REF_CLEAN"] = feature_series.apply(parse_rppa_antibody)

            id_vars = ["HUGO_SYMBOL_CLEAN", "ANTIBODY_REF_CLEAN"]

            long_df = chunk[id_vars + sample_cols].melt(
                id_vars=id_vars,
                value_vars=sample_cols,
                var_name="SAMPLE_BARCODE",
                value_name=value_column_name
            )

            long_df["SAMPLE_BARCODE"] = long_df["SAMPLE_BARCODE"].apply(standardize_sample_barcode)
            long_df["HUGO_SYMBOL"] = long_df["HUGO_SYMBOL_CLEAN"].apply(standardize_gene_symbol)
            long_df["ANTIBODY_REF"] = long_df["ANTIBODY_REF_CLEAN"]
            long_df[value_column_name] = to_numeric_clean(long_df[value_column_name])

            long_df = long_df.dropna(subset=["SAMPLE_BARCODE", "HUGO_SYMBOL", value_column_name])

            long_df = long_df[
                ["SAMPLE_BARCODE", "HUGO_SYMBOL", "ANTIBODY_REF", value_column_name]
            ]

            gene_rows.append(
                long_df[["HUGO_SYMBOL"]].drop_duplicates()
            )

        else:
            chunk["HUGO_SYMBOL_CLEAN"] = get_series(chunk, gene_col).apply(standardize_gene_symbol)

            long_df = chunk[["HUGO_SYMBOL_CLEAN"] + sample_cols].melt(
                id_vars=["HUGO_SYMBOL_CLEAN"],
                value_vars=sample_cols,
                var_name="SAMPLE_BARCODE",
                value_name=value_column_name
            )

            long_df["SAMPLE_BARCODE"] = long_df["SAMPLE_BARCODE"].apply(standardize_sample_barcode)
            long_df["HUGO_SYMBOL"] = long_df["HUGO_SYMBOL_CLEAN"].apply(standardize_gene_symbol)
            long_df[value_column_name] = to_numeric_clean(long_df[value_column_name])

            long_df = long_df.dropna(subset=["SAMPLE_BARCODE", "HUGO_SYMBOL", value_column_name])

            long_df = long_df[
                ["SAMPLE_BARCODE", "HUGO_SYMBOL", value_column_name]
            ]

            gene_rows.append(
                long_df[["HUGO_SYMBOL"]].drop_duplicates()
            )

        long_df.to_csv(
            output_path,
            mode="w" if first_write else "a",
            index=False,
            header=first_write
        )

        total_rows += len(long_df)
        first_write = False

        print(f"{output_filename}: processed rows {start:,} to {min(start + chunk_size, len(df)):,}")

    if len(gene_rows) > 0:
        gene_source = pd.concat(gene_rows, ignore_index=True).drop_duplicates()
        gene_source["ENTREZ_GENE_ID"] = pd.NA
        gene_source = gene_source[["HUGO_SYMBOL", "ENTREZ_GENE_ID"]]
    else:
        gene_source = pd.DataFrame(columns=["HUGO_SYMBOL", "ENTREZ_GENE_ID"])

    gene_source_file = OUTPUT_DIR / gene_source_name
    gene_source.to_csv(gene_source_file, index=False)

    print(f"Saved {output_filename}: {total_rows:,} rows")
    print(f"Saved {gene_source_name}: {len(gene_source):,} genes")

    return gene_source


