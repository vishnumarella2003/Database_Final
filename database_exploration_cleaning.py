def clean_column_name(col):
    """
    Standardizes column names.
    Example:
    Tumor Sample Barcode -> TUMOR_SAMPLE_BARCODE
    """
    col = str(col).strip()
    col = col.replace(" ", "_")
    col = col.replace("-", "_")
    col = col.replace("/", "_")
    col = re.sub(r"[^A-Za-z0-9_]", "", col)
    col = col.upper()

    if col == "":
        col = "UNNAMED_COLUMN"

    return col


def make_unique_columns(columns):
    """
    Ensures duplicate column names are made unique.
    This prevents pandas from returning a DataFrame instead of a Series
    when selecting df[col].
    """
    seen = {}
    unique_cols = []

    for col in columns:
        base = clean_column_name(col)

        if base not in seen:
            seen[base] = 0
            unique_cols.append(base)
        else:
            seen[base] += 1
            unique_cols.append(f"{base}_{seen[base]}")

    return unique_cols


def read_cbioportal_file(filepath):
    """
    Reads a cBioPortal tab-separated file.
    Skips metadata/comment rows beginning with '#'.
    Cleans column names.
    Makes duplicate column names unique.
    Converts missing labels to NaN.
    """

    if not filepath.exists():
        raise FileNotFoundError(f"Missing file: {filepath}")

    df = pd.read_csv(
        filepath,
        sep="\t",
        comment="#",
        dtype=str,
        low_memory=False
    )

    df.columns = make_unique_columns(df.columns)
    df = df.replace(MISSING_VALUES, np.nan)

    return df


def find_column(df, candidates):
    """
    Finds the first matching column from candidate column names.
    """
    cols = list(df.columns)

    for c in candidates:
        cc = clean_column_name(c)
        if cc in cols:
            return cc

    return None


def get_column_as_series(df, col):
    """
    Safely returns a column as a Series.
    If duplicate columns somehow still exist, takes the first one.
    """
    obj = df[col]

    if isinstance(obj, pd.DataFrame):
        return obj.iloc[:, 0]

    return obj


def derive_patient_barcode_from_sample(sample_barcode):
    """
    TCGA patient barcode is usually first 12 characters.
    Example:
    TCGA-05-4244-01 -> TCGA-05-4244
    """
    if pd.isna(sample_barcode):
        return np.nan

    sample_barcode = str(sample_barcode).strip()

    if sample_barcode.startswith("TCGA") and len(sample_barcode) >= 12:
        return sample_barcode[:12]

    return sample_barcode


def summarize_missingness(df, dataset_name):
    """
    Summarizes missingness, unique values, and example values for each column.
    Fixed to safely handle duplicate column names.
    """

    rows = []

    for col in df.columns:
        series = get_column_as_series(df, col)

        non_null_count = int(series.notna().sum())
        null_count = int(series.isna().sum())
        missing_percent = round(float(series.isna().mean() * 100), 2)
        unique_values = int(series.nunique(dropna=True))

        example_values = ", ".join(
            series.dropna().astype(str).unique()[:5]
        )

        rows.append({
            "DATASET": dataset_name,
            "COLUMN": col,
            "NON_NULL_COUNT": non_null_count,
            "NULL_COUNT": null_count,
            "MISSING_PERCENT": missing_percent,
            "UNIQUE_VALUES": unique_values,
            "EXAMPLE_VALUES": example_values
        })

    return pd.DataFrame(rows).sort_values(["MISSING_PERCENT", "COLUMN"])


