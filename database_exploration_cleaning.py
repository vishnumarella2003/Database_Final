def identify_matrix_gene_column(df):
    """
    Finds the gene or feature column in matrix-style files.
    If no recognized gene column exists, uses the first column.
    """
    gene_col = find_column(df, ["HUGO_SYMBOL", "GENE", "GENE_SYMBOL", "COMPOSITE_ELEMENT_REF"])

    if gene_col is not None:
        return gene_col

    return df.columns[0]


def get_gene_symbols_from_matrix(df):
    gene_col = identify_matrix_gene_column(df)
    s = get_column_as_series(df, gene_col)

    return set(s.dropna().astype(str).str.upper().str.strip())


def get_sample_ids_from_matrix(df):
    """
    Gets sample IDs from matrix-style files.
    Excludes likely annotation columns.
    """

    gene_col = identify_matrix_gene_column(df)

    id_cols = [gene_col]

    possible_annotation_cols = [
        "ENTREZ_GENE_ID",
        "GENE_ID",
        "CYTOBAND",
        "DESCRIPTION",
        "ANTIBODY_REF",
        "PROTEIN_NAME",
        "RPPA_ID",
        "COMPOSITE_ELEMENT_REF",
        "ENTITY_STABLE_ID",
        "REFSEQ_PROTEIN_ID"
    ]

    for col in possible_annotation_cols:
        c = clean_column_name(col)
        if c in df.columns and c not in id_cols:
            id_cols.append(c)

    sample_cols = [c for c in df.columns if c not in id_cols]

    return set(sample_cols)


def get_driver_gene_presence(gene_sets):
    rows = []

    for gene in DRIVER_GENES:
        row = {"GENE": gene}

        for dataset_name, genes in gene_sets.items():
            row[dataset_name] = "YES" if gene in genes else "NO"

        rows.append(row)

    return pd.DataFrame(rows)


def recommend_column_status(column_name):
    """
    Gives a rough recommendation for whether a column may be useful.
    """

    col = column_name.upper()

    high_value_keywords = [
        "PATIENT", "SAMPLE", "BARCODE", "SEX", "GENDER", "AGE",
        "OS", "SURVIVAL", "STATUS", "MONTHS",
        "STAGE", "TUMOR", "METASTASIS", "SMOKING",
        "HISTOLOGICAL", "CANCER_TYPE", "SUBTYPE",
        "TMB", "MUTATION_COUNT", "FRACTION_GENOME_ALTERED",
        "HUGO", "ENTREZ", "CHROMOSOME", "START", "END",
        "VARIANT", "ALLELE", "CONSEQUENCE", "IMPACT",
        "PROTEIN", "CODON", "T_ALT", "T_REF"
    ]

    derived_or_complex_keywords = [
        "Z_SCORE", "ZSCORE", "P_VALUE", "Q_VALUE",
        "URL", "LINK", "COMMENT", "NOTES"
    ]

    if any(k in col for k in derived_or_complex_keywords):
        return "LOW PRIORITY / POSSIBLY EXCLUDE"

    if any(k in col for k in high_value_keywords):
        return "KEEP / REVIEW FOR DATABASE"

    return "REVIEW"


def make_column_decision_summary(df, dataset_name):
    missing = summarize_missingness(df, dataset_name)
    missing["RECOMMENDATION"] = missing["COLUMN"].apply(recommend_column_status)
    return missing


def save_df(df, filename):
    path = OUTPUT_DIR / filename
    df.to_csv(path, index=False)
    return path


